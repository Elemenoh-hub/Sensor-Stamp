package com.sensorstamp.openwifi.data

/** Builds an [Observation] with sensible defaults so tests only state what matters. */
fun observation(
    bssid: String = "aa:bb:cc:11:22:33",
    ssid: String = "TestNet",
    rssi: Int = -60,
    latitude: Double = 51.5000,
    longitude: Double = -0.1000,
    observedAt: Long = 1_700_000_000_000L,
    sessionId: Long = 1L,
    capabilities: String = "[ESS]",
    securityType: String = "OPEN",
    frequencyMhz: Int = 2437,
    channel: Int = 6,
    band: String = "2.4 GHz",
    channelWidthMhz: Int = 20,
    centerFreq0: Int = 0,
    centerFreq1: Int = 0,
    wifiStandard: Int = 0,
    supportsFtm: Boolean = false,
    isPasspoint: Boolean = false,
    isHidden: Boolean = false,
    venueHint: String? = null,
    accuracyM: Float = 8f,
): Observation = Observation(
    bssid = bssid,
    ssid = ssid,
    capabilities = capabilities,
    securityType = securityType,
    rssi = rssi,
    frequencyMhz = frequencyMhz,
    channel = channel,
    band = band,
    channelWidthMhz = channelWidthMhz,
    centerFreq0 = centerFreq0,
    centerFreq1 = centerFreq1,
    wifiStandard = wifiStandard,
    supportsFtm = supportsFtm,
    isPasspoint = isPasspoint,
    isHidden = isHidden,
    venueHint = venueHint,
    latitude = latitude,
    longitude = longitude,
    accuracyM = accuracyM,
    altitudeM = 0.0,
    speedMps = 0f,
    bearingDeg = 0f,
    locationProvider = "fused",
    locationAgeMs = 100L,
    scanTimestampMicros = 0L,
    observedAt = observedAt,
    sessionId = sessionId,
)
